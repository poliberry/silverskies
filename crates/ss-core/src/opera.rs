//! European weather radars in EUMETNET OPERA (from OPERA's station list),
//! whose scans the Open Radar Data service publishes: ODIM code (`deess`:
//! country + site), place, country and position.

/// One OPERA radar.
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct OperaRadar {
    /// ODIM code, lower case (`deess`).
    pub code: &'static str,
    pub name: &'static str,
    pub country: &'static str,
    pub lat: f64,
    pub lon: f64,
}

/// A radar by ODIM code (any case).
pub fn find(code: &str) -> Option<&'static OperaRadar> {
    RADARS.iter().find(|r| r.code.eq_ignore_ascii_case(code))
}

/// Is this an OPERA radar code (as opposed to a NEXRAD id like `KTLX`)?
pub fn is_opera(code: &str) -> bool {
    find(code).is_some()
}

